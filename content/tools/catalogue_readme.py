w('4. **Bottoms.** Forty-six, against 119 tops and 106 layers. Trousers and skirts in')
w('   rust, olive and ochre specifically.')
w('5. **Flat packshots instead of listing grids.** 144 products exist only inside a')
w('   grid screenshot. One tap into the product page turns each of them into a piece')
w('   that can go on a board.\n')
w('## How validation will work\n')
w('Nothing to do here today. When you want to start checking rows: filter')
w('`products.csv` by `used_in`, which lists the boards a product has appeared on, so')
w('the pieces that have actually been published come first. Fill in `validated`')
w('yourself — a date, or your initials, whatever suits. A later run reads that column,')
w('leaves anything validated alone, and refreshes names, brands and links for')
w('everything else from the catalogue. Every board and every Note references a')
w('`product_id`, so a correction made once flows to all of them.\n')
open(ROOT+'/content/catalogue/README.md','w').write('\n'.join(L)+'\n')
